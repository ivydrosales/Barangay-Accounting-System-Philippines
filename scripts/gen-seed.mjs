// Turns data/chart_of_accounts.csv into supabase/seed.sql.
// The CSV is the source of truth (verified code-for-code against the manual);
// run `npm run seed:gen` after any change to it. Never edit seed.sql by hand.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const csvPath = join(root, "data", "chart_of_accounts.csv");
const outPath = join(root, "supabase", "seed.sql");

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') inQuotes = false;
      else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c !== "\r") field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const text = readFileSync(csvPath, "utf8").replace(/^﻿/, "");
const [header, ...records] = parseCsv(text).filter((r) => r.length > 1);
const expected = ["account_code", "account_title", "class", "group", "sub_group",
  "normal_balance", "contra_of", "statement_line", "subsidiary_ledger"];
if (header.join(",") !== expected.join(",")) {
  throw new Error(`unexpected CSV header: ${header.join(",")}`);
}

const q = (v) => (v === "" ? "null" : `'${v.replace(/'/g, "''")}'`);
const codes = new Set(records.map((r) => r[0]));
for (const r of records) {
  if (!/^[1-5]-\d{2}-\d{2}-\d{3}$/.test(r[0])) throw new Error(`bad account code ${r[0]}`);
  if (r[6] && !codes.has(r[6])) throw new Error(`${r[0]} is contra of unknown ${r[6]}`);
}

// Contra accounts reference their parent, so parents must land first.
const ordered = [...records.filter((r) => !r[6]), ...records.filter((r) => r[6])];

const lines = [
  "-- Generated by scripts/gen-seed.mjs from data/chart_of_accounts.csv. Do not edit.",
  `-- ${records.length} accounts, COA Manual on the Financial Management of Barangays (2018), Chapter XIII.`,
  "",
  "insert into account (code, title, class, account_group, sub_group, normal_balance, contra_of, statement_line, subsidiary_ledger) values",
  ordered
    .map((r) => `  (${q(r[0])}, ${q(r[1])}, ${q(r[2])}, ${q(r[3])}, ${q(r[4])}, ${q(r[5])}, ${q(r[6])}, ${q(r[7])}, ${q(r[8])})`)
    .join(",\n"),
  "on conflict (code) do update set",
  "  title = excluded.title, class = excluded.class, account_group = excluded.account_group,",
  "  sub_group = excluded.sub_group, normal_balance = excluded.normal_balance, contra_of = excluded.contra_of,",
  "  statement_line = excluded.statement_line, subsidiary_ledger = excluded.subsidiary_ledger;",
  "",
];

writeFileSync(outPath, lines.join("\n"));
console.log(`wrote ${outPath} with ${records.length} accounts`);
